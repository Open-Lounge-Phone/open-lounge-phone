function coordinator(env: Env): Coordinator {
  return {
    isOnline: (hh, deviceId) => env.HOUSEHOLD.getByName(hh).isOnline(deviceId),
    refreshDevice: (hh, deviceId) => env.HOUSEHOLD.getByName(hh).refreshDevice(deviceId),
    notifyPaired: (code, device) =>
      env.PAIRING.getByName(PAIRING_OBJECT).notifyPaired(code, device),
    announce: (hh, msg) => env.HOUSEHOLD.getByName(hh).announce(msg),
    forgetDevice: (hh, deviceId) => env.HOUSEHOLD.getByName(hh).forgetDevice(deviceId),
    notifyAccount: async (accountId, msg) => {
      const store = new Store(d1Sql(env.DB));
      for (const m of await store.listMemberships(accountId)) {
        await env.HOUSEHOLD.getByName(m.household.id).notifyUser(m.user.id, msg);
      }
    },
  };
}

const isId = (s: string | null): s is string => s !== null && Id.safeParse(s).success;

const app = new Hono<{ Bindings: Env }>();

app.use("/api/setup", async (c, next) => {
  if (c.env.SETUP_TOKEN)
    await seedSetupToken(
      serverEnv(c.env, (p) => c.executionCtx.waitUntil(p)),
      c.env.SETUP_TOKEN,
    );
  await next();
});

// Server-to-server: the published key and the signed /fed/v1 endpoints.
const federation = (c: Context<{ Bindings: Env }>) =>
  federationApp(
    serverEnv(c.env, (p) => c.executionCtx.waitUntil(p)),
    coordinator(c.env),
  ).fetch(c.req.raw);
app.get("/.well-known/openloungephone", (c) => federation(c));
app.all("/fed/v1/*", (c) => federation(c));

app.all("/api/*", (c) => {
  const api = new Hono().route(
    "/api",
    createApi(
      serverEnv(c.env, (p) => c.executionCtx.waitUntil(p)),
      coordinator(c.env),
    ),
  );
  return api.fetch(c.req.raw, c.env, c.executionCtx);
});

// Sockets are routed by a hint in the URL; the object still authenticates every connection. An
// app socket goes to the household it names; the object only accepts it when the session's
// account is a member of that household.
app.get("/ws/device", async (c) => {
  const deviceId = c.req.query("device") ?? null;
  const device = isId(deviceId) ? await new Store(d1Sql(c.env.DB)).getDevice(deviceId) : undefined;
  const stub = device
    ? c.env.HOUSEHOLD.getByName(device.householdId)
    : c.env.PAIRING.getByName(PAIRING_OBJECT);
  return stub.fetch(c.req.raw);
});

app.get("/ws/app", async (c) => {
  const householdId = c.req.query("household") ?? null;
  if (!isId(householdId)) return c.text("missing ?household=", 400);
  if (!(await new Store(d1Sql(c.env.DB)).getHousehold(householdId))) {
    return c.text("unknown household", 404);
  }
  return c.env.HOUSEHOLD.getByName(householdId).fetch(c.req.raw);
});

app.all("*", (c) => c.env.ASSETS.fetch(c.req.raw));

export default app satisfies ExportedHandler<Env>;
