export interface Env {
  DB: D1Database;
  /** Voicemail audio. */
  BLOBS: R2Bucket;
  /** Optional Workers AI binding for voicemail transcripts (see docs/cloudflare.md). */
  AI?: Ai;
  HOUSEHOLD: DurableObjectNamespace<HouseholdObject>;
  PAIRING: DurableObjectNamespace<PairingObject>;
  ASSETS: Fetcher;
  SETUP_TOKEN?: string;
  /** "1" = open sign-up (wrangler var; `scripts/deploy.ts --open-signup`). Off by default. */
  OPEN_SIGNUP?: string;
  TURN_KEY_ID?: string;
  TURN_KEY_API_TOKEN?: string;
  /** Comma-separated; used when no TURN key is configured. */
  STUN_URLS?: string;
  /** `https://<domain>`: the host in `handle@host` and in federation signatures (deploy.ts). */
  PUBLIC_URL?: string;
  /** This server's federation key (Ed25519 private JWK JSON), generated by deploy.ts. */
  FED_PRIVATE_KEY?: string;
}

