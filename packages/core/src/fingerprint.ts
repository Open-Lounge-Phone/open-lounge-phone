/** The four words for a key's SHA-256 digest (at least 4 bytes). Pure. */
export function fingerprintWords(digest: Uint8Array): [string, string, string, string] {
  if (digest.length < 4) throw new Error("digest too short");
  const w = (i: number) => FINGERPRINT_WORDS[digest[i] as number] as string;
  return [w(0), w(1), w(2), w(3)];
}

/** The four words for a raw public key, as base64url (how the protocol carries it). */
export async function deviceFingerprint(
  publicKeyBase64Url: string,
): Promise<[string, string, string, string]> {
  const b64 = publicKeyBase64Url.replace(/-/g, "+").replace(/_/g, "/");
  const bin = atob(b64 + "=".repeat((4 - (b64.length % 4)) % 4));
  const raw = Uint8Array.from(bin, (c) => c.charCodeAt(0));
  return fingerprintWords(new Uint8Array(await crypto.subtle.digest("SHA-256", raw)));
}
