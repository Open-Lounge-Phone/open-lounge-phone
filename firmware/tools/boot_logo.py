"""The boot screen's mark -> firmware/main/boot_logo.h (a 1-bit bitmap, 1 = black).

The site's app icon (website public/favicon.svg) drawn crisply at 72 px for e-paper: a black
rounded square, a white handset (two cups and a curved grip) over the keypad's two rows of six.

    python3 tools/boot_logo.py      # needs Pillow
"""
from pathlib import Path

from PIL import Image, ImageDraw

S = 72
K = S / 512                          # the icon's 512-unit grid -> pixels
OUT = Path(__file__).resolve().parent.parent / "main" / "boot_logo.h"


def main() -> None:
    big = 8                          # draw large, then reduce: clean edges at 1 bit
    img = Image.new("L", (S * big, S * big), 255)
    d = ImageDraw.Draw(img)
    u = lambda v: v * K * big
    d.rounded_rectangle([0, 0, S * big - 1, S * big - 1], radius=u(112), fill=0)
    d.arc([u(128), u(132), u(384), u(300)], 200, 340, fill=255, width=int(u(44)))
    d.rounded_rectangle([u(92), u(192), u(212), u(262)], radius=u(34), fill=255)
    d.rounded_rectangle([u(300), u(192), u(420), u(262)], radius=u(34), fill=255)
    for row, y in enumerate((300, 356)):
        for col in range(6):
            x = 92 + col * 56
            w = 46 if col < 5 else 52
            d.rounded_rectangle([u(x), u(y), u(x + w), u(y + 44)], radius=u(10), fill=255)
    small = img.resize((S, S), Image.LANCZOS).point(lambda v: 0 if v < 128 else 255)
    px = small.load()
    row_bytes = (S + 7) // 8
    data = bytearray(row_bytes * S)
    for y in range(S):
        for x in range(S):
            if px[x, y] == 0:
                data[y * row_bytes + x // 8] |= 0x80 >> (x % 8)
    lines = ", ".join(f"0x{b:02X}" for b in data)
    OUT.write_text(
        "// Generated by tools/boot_logo.py from the site's app icon: don't edit.\n#pragma once\n"
        "#include <stdint.h>\n\n"
        f"#define BOOT_LOGO_W {S}\n#define BOOT_LOGO_H {S}\n"
        f"static const uint8_t BOOT_LOGO[{len(data)}] = {{{lines}}};\n")
    small.resize((S * 4, S * 4), Image.NEAREST).save(OUT.with_suffix(".png").parent.parent / "build" / "boot_logo.png")
    print(OUT)


if __name__ == "__main__":
    main()
